#!/usr/bin/env python3
"""Index helpers for the .deb re-pin (FEAT-6.104.1).

  debs-index.py verify --inrelease F --path P --file G
      G must hash to the SHA256 (and size) the Release file lists for path P.
  debs-index.py merge --main IDX --security IDX --out OUT
      one Packages text; the higher version of a package wins; each stanza
      carries X-Origin: main or security so its URL is built under its own
      snapshot.
  debs-index.py lock --jsonl J --base-url U --main-snapshot T --security-snapshot T \
      --arch A --out LOCK
"""
import argparse
import hashlib
import importlib.util
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("chk", os.path.join(here, "guest-debs-check.py"))
chk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(chk)


def signed_text(raw):
    """The text a clearsigned InRelease signs, or None. The file must be exactly one signed block:
    nothing before the header, nothing after the signature, one header, one signature."""
    text = open(raw, errors="replace").read()
    head, sig, end = "-----BEGIN PGP SIGNED MESSAGE-----", "-----BEGIN PGP SIGNATURE-----", "-----END PGP SIGNATURE-----"
    lines = text.rstrip("\n").split("\n")
    if not lines or lines[0] != head or lines[-1] != end or lines.count(head) != 1 or lines.count(sig) != 1:
        return None
    try:
        start = lines.index("", 1) + 1  # the blank line ends the armor headers (Hash:)
    except ValueError:
        return None
    body = lines[start:lines.index(sig)]
    return [l[2:] if l.startswith("- ") else l for l in body]  # undo dash-escaping


def verify(inrelease, path, file, suite=None):
    """inrelease is the raw clearsigned file the signature check passed; only its signed text is read."""
    body = signed_text(inrelease)
    if body is None:
        print("the InRelease is not exactly one signed block", file=sys.stderr)
        return 1
    if suite is not None:
        names = {l.split(":", 1)[1].strip() for l in body if l.startswith(("Suite:", "Codename:"))}
        if suite not in names:
            print(f"the Release names {sorted(names)}, not {suite}", file=sys.stderr)
            return 1
    want = None
    in_sha = False
    for line in body:
        if line.startswith("SHA256:"):
            in_sha = True
            continue
        if in_sha:
            if not line.startswith(" "):
                in_sha = False
                continue
            parts = line.split()
            if len(parts) == 3 and parts[2] == path:
                want = (parts[0], int(parts[1]))
                break
    if want is None:
        print(f"{path}: not listed in the Release file", file=sys.stderr)
        return 1
    data = open(file, "rb").read()
    got = (hashlib.sha256(data).hexdigest(), len(data))
    if got != want:
        print(f"{path}: hash or size differs from the Release file (listed {want[0][:16]}.., got {got[0][:16]}..)", file=sys.stderr)
        return 1
    return 0


def merge(main, security, out):
    best = {}
    for origin, path in (("main", main), ("security", security)):
        for d in chk.stanzas(open(path).read()):
            p = d["Package"]
            d["X-Origin"] = origin
            if p not in best or chk.compare(d["Version"], best[p]["Version"]) > 0:
                best[p] = d
    with open(out, "w") as f:
        for p in sorted(best):
            for k, v in best[p].items():
                f.write(f"{k}: {v}\n")
            f.write("\n")
    return 0


def lock(jsonl, base, mts, sts, arch, out):
    import json
    with open(out, "w") as f:
        f.write(f"""# Pinned .deb files that add git and make to the Debian slim guest base
# (FEAT-6.104). The slim image has neither and the guest has no network, so the
# base build fetches these, verifies each sha256, and unpacks them into the tree.
# One line per package: <package> <version> <sha256> <url>. Generated by
# repin-guest-debs.sh from the signed bookworm and bookworm-security indexes of
# the two snapshots below (the higher version of a package wins), as the
# packages git and make need that the slim base does not already carry. A
# refresh changes both timestamps and every affected line together.
# snapshot main: {base}/archive/debian/{mts}/
# snapshot security: {base}/archive/debian-security/{sts}/
""")
        for line in open(jsonl):
            d = json.loads(line)
            sub = f"debian-security/{sts}" if d["origin"] == "security" else f"debian/{mts}"
            f.write(f"{d['package']} {d['version']} {d['sha256']} {base}/archive/{sub}/{d['file']}\n")
    return 0


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("verify")
    v.add_argument("--inrelease", required=True)
    v.add_argument("--path", required=True)
    v.add_argument("--file", required=True)
    v.add_argument("--suite")
    m = sub.add_parser("merge")
    m.add_argument("--main", required=True)
    m.add_argument("--security", required=True)
    m.add_argument("--out", required=True)
    l = sub.add_parser("lock")
    l.add_argument("--jsonl", required=True)
    l.add_argument("--base-url", required=True)
    l.add_argument("--main-snapshot", required=True)
    l.add_argument("--security-snapshot", required=True)
    l.add_argument("--arch", required=True)
    l.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.cmd == "verify":
        return verify(a.inrelease, a.path, a.file, a.suite)
    if a.cmd == "merge":
        return merge(a.main, a.security, a.out)
    return lock(a.jsonl, a.base_url, a.main_snapshot, a.security_snapshot, a.arch, a.out)


if __name__ == "__main__":
    sys.exit(main())
